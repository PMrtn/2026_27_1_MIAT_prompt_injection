def _text(
    slide: Slide,
    box: tuple[float, float, float, float],
    runs: list[tuple[str, dict[str, object]]],
    *,
    align: PP_ALIGN = PP_ALIGN.LEFT,
    anchor: MSO_ANCHOR = MSO_ANCHOR.TOP,
    name: str = "",
) -> None:
    """A text box; ``runs`` is a list of paragraphs, each (text, style) with keys size/bold/color/font/italic."""
    shape = slide.shapes.add_textbox(*(Inches(v) for v in box))
    if name:
        shape.name = name
    frame = shape.text_frame
    frame.word_wrap = True
    frame.vertical_anchor = anchor
    frame.margin_left = frame.margin_right = frame.margin_top = frame.margin_bottom = Emu(0)
    for index, (text, style) in enumerate(runs):
        paragraph = frame.paragraphs[0] if index == 0 else frame.add_paragraph()
        paragraph.alignment = align
        paragraph.space_after = Pt(style.get("after", 6))
        run = paragraph.add_run()
        run.text = text
        font = run.font
        font.size = Pt(style.get("size", 16))
        font.bold = style.get("bold", False)
        font.italic = style.get("italic", False)
        font.name = style.get("font", BODY)
        font.color.rgb = style.get("color", INK_2)


def _rect(
    slide: Slide, box: tuple[float, float, float, float], fill: RGBColor, rounded: bool = True, name: str = ""
) -> Shape:
    shape = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE if rounded else MSO_SHAPE.RECTANGLE, *(Inches(v) for v in box)
    )
    shape.fill.solid()
    shape.fill.fore_color.rgb = fill
    shape.line.fill.background()
    shape.shadow.inherit = False
    if rounded:
        shape.adjustments[0] = 0.08
    if name:
        shape.name = name
    return shape


def _dot(slide: Slide, x: float, y: float, color: RGBColor, size: float = 0.22) -> None:
    dot = slide.shapes.add_shape(MSO_SHAPE.OVAL, Inches(x), Inches(y), Inches(size), Inches(size))
    dot.fill.solid()
    dot.fill.fore_color.rgb = color
    dot.line.fill.background()
    dot.shadow.inherit = False


def _background(slide: Slide, color: RGBColor) -> None:
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = color


def _title(slide: Slide, text: str, color: RGBColor = INK) -> None:
    _text(
        slide, (0.6, 0.45, 12.1, 0.9), [(text, {"size": 34, "bold": True, "font": HEAD, "color": color})], name="Title"
    )


def _picture(slide: Slide, name: str, box: tuple[float, float, float]) -> None:
    """Figure scaled to width box[2], placed at (box[0], box[1])."""
    slide.shapes.add_picture(str(FIGURES / f"{name}.png"), Inches(box[0]), Inches(box[1]), width=Inches(box[2]))


def _stat(slide: Slide, x: float, y: float, w: float, value: str, label: str, color: RGBColor) -> None:
    _rect(slide, (x, y, w, 1.95), TINT)
    _text(
        slide, (x + 0.25, y + 0.18, w - 0.5, 0.75), [(value, {"size": 36, "bold": True, "color": color, "font": HEAD})]
    )
    _text(slide, (x + 0.25, y + 0.95, w - 0.5, 0.9), [(label, {"size": 14, "color": INK_2})])


def slide_title(prs: PresentationType) -> None:
    """1. Title and the question."""
